package skim

import (
	"path"
	"strings"
)

// Rule names one kind of fold. The order of the constants is the order in
// which summaries list them.
type Rule string

const (
	Lockfile   Rule = "lockfile"
	Generated  Rule = "generated"
	Whitespace Rule = "whitespace-only"
	Imports    Rule = "import-only"
	Format     Rule = "format-only"
)

// Rules lists every rule in summary order.
var Rules = []Rule{Lockfile, Generated, Whitespace, Imports, Format}

// LockfileNames are the base names folded by the lockfile rule. The baseline
// excludes the same names, so the lockfile rule adds nothing over it.
var LockfileNames = []string{
	"package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
	"bun.lock", "bun.lockb", "deno.lock", "go.sum", "go.work.sum", "Cargo.lock",
	"Gemfile.lock", "composer.lock", "poetry.lock", "uv.lock", "Pipfile.lock",
	"pdm.lock", "flake.lock", "Package.resolved", "Podfile.lock", "pubspec.lock",
	"mix.lock", "packages.lock.json", "gradle.lockfile", ".terraform.lock.hcl",
}

func isLockfile(p string) bool {
	base := path.Base(p)
	for _, n := range LockfileNames {
		if base == n {
			return true
		}
	}
	return false
}

// generatedSuffixes mark files that tools write, by name alone.
var generatedSuffixes = []string{
	".pb.go", "_pb2.py", "_pb2.pyi", "_pb2_grpc.py", ".min.js", ".min.css",
	".js.map", ".css.map", ".snap",
}

// generatedByName returns the matching pattern, or "".
func generatedByName(p string) string {
	if strings.Contains("/"+p, "/__snapshots__/") {
		return "__snapshots__/"
	}
	for _, s := range generatedSuffixes {
		if strings.HasSuffix(p, s) {
			return "*" + s
		}
	}
	return ""
}

// generatedMarker looks for the usual "this file is generated" comments in
// the first lines of a file, and returns the marker it found, or "".
func generatedMarker(content []byte) string {
	lines := strings.SplitN(string(content), "\n", 6)
	if len(lines) > 5 {
		lines = lines[:5]
	}
	for _, l := range lines {
		for _, m := range []string{"DO NOT EDIT", "@generated", "<auto-generated"} {
			if strings.Contains(l, m) {
				return m
			}
		}
	}
	return ""
}

// whitespaceSensitive files can change meaning when only whitespace changes,
// so the whitespace-only rule leaves them alone (git diff -w does not).
func whitespaceSensitive(p string) bool {
	base := strings.ToLower(path.Base(p))
	if base == "makefile" || base == "gnumakefile" {
		return true
	}
	switch path.Ext(base) {
	case ".py", ".pyi", ".yaml", ".yml", ".mk", ".md", ".markdown", ".rst",
		".haml", ".pug", ".slim", ".sass", ".styl", ".coffee", ".nim", ".tsv",
		".diff", ".patch":
		return true
	}
	return false
}

// whitespaceOnly reports whether the removed and added lines are the same
// lines once all whitespace is stripped from each, as git diff -w sees them.
func whitespaceOnly(removed, added []string) bool {
	if len(removed) != len(added) {
		return false
	}
	for i := range removed {
		if stripSpace(removed[i]) != stripSpace(added[i]) {
			return false
		}
	}
	return true
}

func stripSpace(s string) string {
	return strings.Map(func(r rune) rune {
		switch r {
		case ' ', '\t', '\r', '\v', '\f':
			return -1
		}
		return r
	}, s)
}
